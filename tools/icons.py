"""Generate mixins/proximity_voice/engine/src/icons.rs from Plasmo Voice's icons.

    python tools/icons.py <plasmo-voice checkout>

Each PNG under client/src/main/resources/assets/plasmovoice/textures/icons becomes its pixels as
ARGB words: the mod draws them square by square, as Horizon gives native mods no textures.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
icons = Path(sys.argv[1]) / "client/src/main/resources/assets/plasmovoice/textures/icons"
out = [
    "// Plasmo Voice's icons (https://github.com/plasmoapp/plasmo-voice, LGPL-3.0-only:",
    "// client/src/main/resources/assets/plasmovoice/textures/icons), as ARGB pixels row by row.",
    "// Generated by tools/icons.py; do not edit.",
    "",
    "/// An icon: its name (its path under `icons/`, without `.png`), side and pixels.",
    "pub struct Icon {",
    "    pub name: &'static str,",
    "    pub size: usize,",
    "    pub pixels: &'static [u32],",
    "}",
    "",
    "pub static ICONS: &[Icon] = &[",
]
for path in sorted(icons.rglob("*.png")):
    name = path.relative_to(icons).with_suffix("").as_posix()
    image = Image.open(path).convert("RGBA")
    w, h = image.size
    assert w == h, name
    words = [f"0x{a:02X}{r:02X}{g:02X}{b:02X}" for r, g, b, a in image.getdata()]
    rows = [", ".join(words[i:i + 8]) for i in range(0, len(words), 8)]
    out.append(f'    Icon {{ name: "{name}", size: {w}, pixels: &[')
    out.extend(f"        {row}," for row in rows)
    out.append("    ] },")
out += [
    "];",
    "",
    "/// The icon named `name`, or the one a Plasmo Voice texture path ends in",
    "/// (`plasmovoice:textures/icons/speaker_disc.png`).",
    "pub fn icon(name: &str) -> Option<&'static Icon> {",
    "    let name = name.rsplit_once(\"icons/\").map_or(name, |(_, n)| n);",
    "    let name = name.strip_suffix(\".png\").unwrap_or(name);",
    "    ICONS.iter().find(|i| i.name == name)",
    "}",
    "",
]
(ROOT / "mixins/proximity_voice/engine/src/icons.rs").write_text("\n".join(out), newline="\n")
print(len(list(icons.rglob("*.png"))), "icons")
